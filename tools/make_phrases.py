# ナビが好きな声で話す言葉の一覧（声のパックを作る時の台本）を作る。
# アプリは読み上げる文を「、」「。」で区切り、区切りごとにこの一覧の言葉（またはその組み合わせ）で言えれば好きな声、
# 言えない言葉（地名・IC名など）が1つでもあれば、その文は全部いつもの機械の声で読む。
# 使い方: python3 tools/make_phrases.py  → tools/voice_phrases.json
import json,os
P=[]
def add(*xs):
    for x in xs:
        if x and x not in P:P.append(x)
# 距離
add("まもなく")
for n in range(1,10):add(f"{n}00メートル先",f"{n}00メートル",f"{n}00メートル先から")
for t in range(10,100):
    k=t/10;s=(f"{k:.1f}").rstrip("0").rstrip(".")
    add(f"{s}キロ先",f"{s}キロ",f"{s}キロ先から")
for k in range(10,51):add(f"{k}キロ先",f"{k}キロ",f"{k}キロ先から")
# 曲がる・分岐（経路検索の案内文から地名を除いた形）
dirs=["右方向","左方向","直進","Uターン","斜め右手前方向","斜め左手前方向"]
for d in dirs:add(d,d+"です")
for d in ["右","左"]:
    add(f"分岐を{d}方向",f"分岐を{d}方向です",f"{d}方向に合流",f"{d}方向に合流です",f"目的地は{d}側です")
add("分岐を直進","分岐を直進です","分岐","分岐です","出口","出口です","合流","合流です","目的地","目的地です",
    "環状交差点に入ります","環状交差点を出ます","右折","左折","右折です","左折です")
# 車線
lanes=["左車線","右車線","中央車線","左2車線","右2車線","左3車線","右3車線","中央2車線","中央3車線","左折レーン","右折レーン",
       "左2車線の左折レーン","右2車線の右折レーン","左から2番目の車線","左から3番目の車線"]
for l in lanes:add(l+"を走行してください")
add("この先","左車線は","右車線は","左折専用レーンになります","右折専用レーンになります")
# 料金所・続く分岐
add("この先、料金所です".split("、")[1],"抜けたら","料金所を出たら","続いて")
# 速度取り締まり
add("速度取り締まり機があります")
for v in range(30,130,10):add(f"制限速度{v}キロです")
# 冬期閉鎖（名前があるので機械の声になるが、名前なしの時用）
add("冬期閉鎖の区間です","通れない場合は再検索してください")
# 渋滞・迂回
add("から渋滞","から混雑","迂回すると","迂回しても","到着はほぼ同じです")
for m in range(1,91):add(f"通過に約{m}分",f"約{m}分早く着きます",f"約{m}分遅くなります")
# SA・PAの休憩
add("休憩できるのは","目標の到着時刻まで","余裕がありません")
for m in range(1,181):add(f"{m}分")
for h in range(0,24):add(f"{h}時")
for m in range(0,60):add(f"{m}分までです")
# トンネル
add("この先のトンネル内で")
for n in range(1,10):add(f"分岐が{n}か所あります",f"{n}つ目")
# 指定速度
add("指定速度")
for v in range(30,145,5):add(f"{v}")
# 決まった言葉
add("案内を開始します","目的地に到着しました","目的地まで半分を過ぎました","迂回ルートにしました","音声案内をオンにしました",
    "アクセルを離してください","高速道路に入りました","一般道に入りました","立ち寄りをやめました","サービスエリア","パーキングエリア",
    "ルートを外れました","再検索します","新しいルートで案内します")
out=[{"id":f"p{i:04d}","text":t} for i,t in enumerate(P)]
json.dump(out,open(os.path.join(os.path.dirname(__file__),"voice_phrases.json"),"w"),ensure_ascii=False,indent=0)
print(len(out),"phrases")
